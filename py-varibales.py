# main data type in python are
# int, float, str, bool, list, tuple, set, dict, None
print(type(5))  # int
print(type("joba")) # str

# list >>> Ordered, mutable, allows duplicate elements
my_list = [1, 2, 3, 4, 5]
print(type(my_list)) # list

# tuple >>> Ordered, immutable, allows duplicate elements
my_tuple = (1, 2, 3, 4, 5)
print(type(my_tuple)) # tuple

# dict >>> Unordered, mutable, does not allow duplicate keys
my_dict = {"name": "joba", "age": 25}
print(type(my_dict)) # dict

# set >>> Unordered, mutable, does not allow duplicate elements
my_set = {1, 2, 3, 4, 5}
print(type(my_set)) # set

